def generate_iter1_trajectories(
    model_path: "str | Path",
    task_dataset_path: "str | Path",
    snapshot_root: "str | Path",
    output_path: "str | Path",
    *,
    max_tasks: "int | None" = DEFAULT_MAX_TASKS,
    max_turns: int = 10,
    temperature: float = 0.7,
) -> int:
    """Drive the iter0 model through tasks; write scored ReAct trajectories as JSONL.

    Each line: {"messages": [...], "reward": float}. Returns the count written.
    Never raises -- returns 0 on any setup failure so the caller falls back.
    """
    gen = _build_generator(model_path)
    if gen is None:
        return 0
    try:
        from our_envs.intercode_local_bash_env import (
            LocalBashEnv,
            detect_fs_for_gold,
            is_safe_for_real_exec,
        )
    except Exception as exc:
        print(f"[intercode_iter1_gen] sandbox import failed: {exc}", flush=True)
        return 0

    tasks = _load_tasks(task_dataset_path, max_tasks)
    if not tasks:
        print("[intercode_iter1_gen] no tasks loaded; skipping iter1 gen.", flush=True)
        return 0

    written = 0
    try:
        with open(output_path, "w", encoding="utf-8") as fout:
            for i, (query, gold) in enumerate(tasks):
                try:
                    fs = detect_fs_for_gold(gold)
                    if fs == -1 or not is_safe_for_real_exec(gold):
                        continue
                    env = LocalBashEnv(fs_version=fs, snapshot_root=snapshot_root)
                    env.reset()
                    messages, last_obs, did_submit = _react_rollout(
                        gen, query, env, max_turns, temperature
                    )
                    gold_obs = _gold_observation(gold, fs, LocalBashEnv, snapshot_root)
                    if gold_obs is None:
                        continue
                    reward = _token_cosine(last_obs, gold_obs) if did_submit else 0.0
                    fout.write(json.dumps({"messages": messages, "reward": reward}) + "\n")
                    written += 1
                    if written % 100 == 0:
                        print(f"[intercode_iter1_gen] wrote {written} trajectories "
                              f"(task {i + 1}/{len(tasks)})", flush=True)
                except Exception as exc:
                    print(f"[intercode_iter1_gen] task {i} failed: {exc}", flush=True)
                    continue
    except Exception as exc:
        print(f"[intercode_iter1_gen] gen loop aborted: {exc}", flush=True)

    print(f"[intercode_iter1_gen] generated {written}/{len(tasks)} iter1 trajectories.", flush=True)
    return written


def filter_iter1_trajectories(
    raw_path: "str | Path",
    output_path: "str | Path",
    *,
    threshold: float = DEFAULT_REWARD_THRESHOLD,
) -> "tuple[int, int]":
    """Rejection-sample: keep trajectories with reward >= threshold.

    Reads JSONL {"messages", "reward"} from raw_path; writes a DatasetDict with
    {"messages": ...} rows (the tokenize chain's input shape) to output_path.
    Returns (kept, total). Never raises.
    """
    kept_rows: list[dict] = []
    total = 0
    try:
        with open(raw_path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                total += 1
                try:
                    row = json.loads(line)
                except Exception:
                    continue
                if float(row.get("reward", 0.0)) >= threshold and row.get("messages"):
                    kept_rows.append({"messages": row["messages"]})
    except FileNotFoundError:
        print(f"[intercode_iter1_gen] raw path missing: {raw_path}", flush=True)
        return 0, 0
    except Exception as exc:
        print(f"[intercode_iter1_gen] filter read failed: {exc}", flush=True)
        return 0, total

    if not kept_rows:
        print(f"[intercode_iter1_gen] filter kept 0/{total}; nothing to save.", flush=True)
        return 0, total

    try:
        from datasets import Dataset, DatasetDict
        ds = Dataset.from_list(kept_rows)
        if len(kept_rows) > 1:
            frac = min(0.1, max(1.0 / len(kept_rows), 0.01))
            split = ds.train_test_split(test_size=frac, seed=0)
            dd = DatasetDict({"train": split["train"], "validation": split["test"]})
        else:
            dd = DatasetDict({"train": ds, "validation": ds})
        dd.save_to_disk(str(output_path))
    except Exception as exc:
        print(f"[intercode_iter1_gen] filter save failed: {exc}", flush=True)
        return 0, total

    print(f"[intercode_iter1_gen] filter kept {len(kept_rows)}/{total} (reward>={threshold}).", flush=True)
    return len(kept_rows), total


def run_iter1_phase(
    iter0_model_path: "str | Path",
    task_dataset_path: "str | Path",
    snapshot_root: "str | Path",
    iter1_output_path: "str | Path",
    *,
    keep_iter0_fraction: float = DEFAULT_KEEP_ITER0_FRACTION,
    max_tasks: "int | None" = DEFAULT_MAX_TASKS,
    max_turns: int = 10,
    temperature: float = 0.7,
) -> bool:
    """Top-level: generate -> filter -> stash iter1 data at iter1_output_path.

    Returns True when usable iter1 data was written, else False (caller falls back
    to a single-pass SFT). `keep_iter0_fraction` is advisory for the caller when it
    mixes the original gold back in. Never raises.
    """
    if not iter_sft_enabled():
        print("[intercode_iter1_gen] INTERCODE_ITER_SFT=0; skipping iter1.", flush=True)
        return False
    try:
        raw_path = str(Path(iter1_output_path).with_suffix(".raw.jsonl"))
        n = generate_iter1_trajectories(
            iter0_model_path, task_dataset_path, snapshot_root, raw_path,
            max_tasks=max_tasks, max_turns=max_turns, temperature=temperature,
        )
        if n == 0:
            print("[intercode_iter1_gen] no iter1 trajectories; falling back to single-pass.", flush=True)
            return False
        kept, total = filter_iter1_trajectories(raw_path, iter1_output_path)
        if kept == 0:
            print("[intercode_iter1_gen] all iter1 trajectories filtered out; falling back.", flush=True)
            return False
        print(f"[intercode_iter1_gen] iter1 ready: {kept}/{total} trajectories at {iter1_output_path} "
              f"(mix ~{keep_iter0_fraction:.0%} iter0 gold downstream for stability).", flush=True)
        return True
    except Exception as exc:
        print(f"[intercode_iter1_gen] run_iter1_phase failed: {exc}; falling back.", flush=True)
        return False


